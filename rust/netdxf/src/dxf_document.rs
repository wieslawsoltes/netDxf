use std::fs::File;
use std::io::{BufReader, BufWriter, Cursor, Read, Seek, Write};
use std::path::Path;

use crate::blocks::Block;
use crate::collections::{DrawingEntities, SupportFolders, TableObjects};
use crate::dxf_class::DxfClass;
use crate::dxf_object::DxfObject;
use crate::dxf_object_code::DxfObjectCode;
use crate::entities::{DimensionBlock, EntityObject};
use crate::error::{DxfError, Result};
use crate::header::{DxfVersion, HeaderVariables};
use crate::io::{DxfReader, DxfWriter};
use crate::objects::{
    DxfGeoData, DxfMLeaderStyle, DxfStoredSunStudy, DxfSun, DxfTableStyle, Group, ImageDefinition,
    LayerState, Layout, MLineStyle, RasterVariables, UnderlayDefinition,
};
use crate::tables::{
    ApplicationRegistry, DimensionStyle, Layer, Linetype, ShapeStyle, TableObject, TextStyle, View,
    VPort, UCS,
};

/// Represents a DXF document for reading, creating, modifying, and writing AutoCAD DXF files.
///
/// Mirrors `netDxf.DxfDocument`.
#[derive(Clone, Debug, PartialEq)]
pub struct DxfDocument {
    pub object: DxfObject,
    pub name: String,
    pub comments: Vec<String>,
    pub drawing_variables: HeaderVariables,
    pub support_folders: SupportFolders,
    pub classes: Vec<DxfClass>,
    pub thumbnail_image: Vec<u8>,
    pub build_dimension_blocks: bool,
    pub num_handles: u64,

    // Tables
    pub application_registries: TableObjects<ApplicationRegistry>,
    pub blocks: TableObjects<Block>,
    pub dimension_styles: TableObjects<DimensionStyle>,
    pub layers: TableObjects<Layer>,
    pub linetypes: TableObjects<Linetype>,
    pub text_styles: TableObjects<TextStyle>,
    pub shape_styles: TableObjects<ShapeStyle>,
    pub ucss: TableObjects<UCS>,
    pub views: TableObjects<View>,
    pub vports: TableObjects<VPort>,

    // Objects
    pub mline_styles: TableObjects<MLineStyle>,
    pub mleader_styles: TableObjects<DxfMLeaderStyle>,
    pub table_styles: TableObjects<DxfTableStyle>,
    pub image_definitions: TableObjects<ImageDefinition>,
    pub underlay_dgn_definitions: TableObjects<UnderlayDefinition>,
    pub underlay_dwf_definitions: TableObjects<UnderlayDefinition>,
    pub underlay_pdf_definitions: TableObjects<UnderlayDefinition>,
    pub groups: TableObjects<Group>,
    pub layouts: TableObjects<Layout>,
    pub layer_states: TableObjects<LayerState>,
    pub raster_variables: RasterVariables,
    pub geo_data: Option<DxfGeoData>,
    pub sun: Option<DxfSun>,
    pub sun_studies: Vec<DxfStoredSunStudy>,

    // Entities (Model Space)
    pub entities: DrawingEntities,
}

impl DxfDocument {
    /// Creates a new empty `DxfDocument` with default AutoCAD 2000 header variables and standard tables.
    pub fn new() -> Self {
        Self::from_header_variables(HeaderVariables::default())
    }

    /// Creates a new empty `DxfDocument` targeting the specified `DxfVersion`.
    pub fn with_version(version: DxfVersion) -> Self {
        Self::from_header_variables(HeaderVariables::with_version(version))
    }

    pub fn from_header_variables(drawing_variables: HeaderVariables) -> Self {
        let mut doc = Self {
            object: DxfObject::new(DxfObjectCode::UNKNOWN),
            name: String::new(),
            comments: vec!["Dxf file generated by netdxf (Rust)".to_string()],
            drawing_variables,
            support_folders: SupportFolders::new(),
            classes: Vec::new(),
            thumbnail_image: Vec::new(),
            build_dimension_blocks: false,
            num_handles: 100,
            application_registries: TableObjects::new("ApplicationRegistry"),
            blocks: TableObjects::new("Block"),
            dimension_styles: TableObjects::new("DimensionStyle"),
            layers: TableObjects::new("Layer"),
            linetypes: TableObjects::new("Linetype"),
            text_styles: TableObjects::new("TextStyle"),
            shape_styles: TableObjects::new("ShapeStyle"),
            ucss: TableObjects::new("UCS"),
            views: TableObjects::new("View"),
            vports: TableObjects::new("VPort"),
            mline_styles: TableObjects::new("MLineStyle"),
            mleader_styles: TableObjects::new("MLeaderStyle"),
            table_styles: TableObjects::new("TableStyle"),
            image_definitions: TableObjects::new("ImageDefinition"),
            underlay_dgn_definitions: TableObjects::new("UnderlayDgnDefinition"),
            underlay_dwf_definitions: TableObjects::new("UnderlayDwfDefinition"),
            underlay_pdf_definitions: TableObjects::new("UnderlayPdfDefinition"),
            groups: TableObjects::new("Group"),
            layouts: TableObjects::new("Layout"),
            layer_states: TableObjects::new("LayerState"),
            raster_variables: RasterVariables::default(),
            geo_data: None,
            sun: None,
            sun_studies: Vec::new(),
            entities: DrawingEntities::new(),
        };
        doc.add_default_objects();
        doc
    }

    fn add_default_objects(&mut self) {
        self.application_registries
            .add(ApplicationRegistry::default_app_reg());
        self.layers.add(Layer::default_layer());
        self.linetypes.add(Linetype::by_layer());
        self.linetypes.add(Linetype::by_block());
        self.linetypes.add(Linetype::continuous());
        self.text_styles.add(TextStyle::default_style());
        self.dimension_styles.add(DimensionStyle::default_style());
        self.vports.add(VPort::active());
        self.mline_styles.add(MLineStyle::default_style());
        self.mleader_styles.add(DxfMLeaderStyle::default_style());
        self.table_styles.add(DxfTableStyle::default_style());
        self.blocks.add(Block::model_space());
        self.blocks.add(Block::paper_space());
        self.layouts.add(Layout::model_space());
    }

    /// Allocates the next unique hexadecimal handle.
    pub fn next_handle(&mut self) -> String {
        let h = format!("{:X}", self.num_handles);
        self.num_handles += 1;
        self.drawing_variables.handle_seed = format!("{:X}", self.num_handles);
        h
    }

    /// Adds an entity to the document's Model Space, auto-registering referenced layers/linetypes/app-regs.
    pub fn add_entity(&mut self, entity: impl Into<EntityObject>) {
        let mut ent = entity.into();
        if ent.common().object.handle.is_none() {
            ent.common_mut().object.handle = Some(self.next_handle());
        }
        // Ensure referenced layer exists
        let layer_name = ent.common().layer.clone();
        if !layer_name.is_empty() && !self.layers.contains(&layer_name) {
            if let Ok(layer) = Layer::new(&layer_name) {
                self.layers.add(layer);
            }
        }
        // Ensure referenced linetype exists
        let lt_name = ent.common().linetype.clone();
        if !lt_name.is_empty() && !self.linetypes.contains(&lt_name) {
            if let Ok(lt) = Linetype::new(&lt_name) {
                self.linetypes.add(lt);
            }
        }
        // Ensure XData app registries exist
        for xdata in ent.common().object.x_data.values() {
            if !self.application_registries.contains(&xdata.application_registry) {
                if let Ok(app) = ApplicationRegistry::new(&xdata.application_registry) {
                    self.application_registries.add(app);
                }
            }
        }
        self.entities.add(ent);
    }

    /// Assigns handles to all tables, blocks, objects, and entities that don't yet have one.
    pub fn assign_all_handles(&mut self) {
        let mut seed = self.num_handles.max(0x100);
        macro_rules! assign_table {
            ($table:expr) => {
                for item in $table.iter_mut() {
                    if item.table_data().object.handle.is_none() {
                        seed = item.table_data_mut().object.assign_handle(seed);
                    }
                }
            };
        }
        assign_table!(self.application_registries);
        assign_table!(self.vports);
        assign_table!(self.linetypes);
        assign_table!(self.layers);
        assign_table!(self.text_styles);
        assign_table!(self.shape_styles);
        assign_table!(self.views);
        assign_table!(self.ucss);
        assign_table!(self.dimension_styles);
        for block in self.blocks.iter_mut() {
            if block.record.object.handle.is_none() {
                seed = block.record.object.assign_handle(seed);
            }
            if block.table.object.handle.is_none() {
                seed = block.table.object.assign_handle(seed);
            }
            if block.end.object.handle.is_none() {
                seed = block.end.object.assign_handle(seed);
            }
            for e in &mut block.entities {
                if e.common().object.handle.is_none() {
                    seed = e.common_mut().object.assign_handle(seed);
                }
            }
            for attdef in block.attribute_definitions.values_mut() {
                if attdef.object.handle.is_none() {
                    seed = attdef.object.assign_handle(seed);
                }
            }
        }
        assign_table!(self.mline_styles);
        assign_table!(self.mleader_styles);
        assign_table!(self.table_styles);
        assign_table!(self.groups);
        assign_table!(self.layouts);
        assign_table!(self.image_definitions);
        assign_table!(self.underlay_dgn_definitions);
        assign_table!(self.underlay_dwf_definitions);
        assign_table!(self.underlay_pdf_definitions);
        if self.raster_variables.object.handle.is_none() {
            seed = self.raster_variables.object.assign_handle(seed);
        }
        if let Some(geo) = &mut self.geo_data {
            if geo.object.handle.is_none() {
                seed = geo.object.assign_handle(seed);
            }
        }
        if let Some(sun) = &mut self.sun {
            if sun.object.handle.is_none() {
                seed = sun.object.assign_handle(seed);
            }
        }
        for study in &mut self.sun_studies {
            if study.object.handle.is_none() {
                seed = study.object.assign_handle(seed);
            }
        }
        for e in self.entities.all_mut() {
            if e.common().object.handle.is_none() {
                seed = e.common_mut().object.assign_handle(seed);
            }
            if let EntityObject::Insert(ins) = e {
                for a in &mut ins.attributes {
                    if a.object.handle.is_none() {
                        seed = a.object.assign_handle(seed);
                    }
                }
            }
        }
        self.num_handles = seed;
        self.drawing_variables.handle_seed = format!("{seed:X}");
    }

    /// Probes the DXF version and binary flag of a file on disk without loading the full document.
    pub fn check_dxf_file_version(path: impl AsRef<Path>) -> Result<(DxfVersion, bool)> {
        let file = File::open(path)?;
        Self::check_dxf_stream_version(BufReader::new(file))
    }

    /// Probes the DXF version and binary flag from a seekable stream.
    pub fn check_dxf_stream_version<R: Read + Seek>(reader: R) -> Result<(DxfVersion, bool)> {
        DxfReader::check_version(reader)
    }

    /// Loads a DXF document (ASCII or Binary) from a file path.
    pub fn load(path: impl AsRef<Path>) -> Result<Self> {
        let p = path.as_ref();
        let file = File::open(p)?;
        let mut doc = Self::load_from_reader(BufReader::new(file))?;
        if let Some(stem) = p.file_stem().and_then(|s| s.to_str()) {
            doc.name = stem.to_string();
        }
        Ok(doc)
    }

    /// Loads a DXF document (ASCII or Binary) from a seekable reader.
    pub fn load_from_reader<R: Read + Seek>(reader: R) -> Result<Self> {
        DxfReader::read(reader)
    }

    /// Loads a DXF document directly from an in-memory byte slice.
    pub fn load_from_bytes(bytes: &[u8]) -> Result<Self> {
        DxfReader::read(Cursor::new(bytes))
    }

    /// Saves the DXF document as an ASCII DXF file.
    pub fn save(&mut self, path: impl AsRef<Path>) -> Result<()> {
        self.save_with_options(path, false)
    }

    /// Saves the DXF document to a file path in either ASCII (`is_binary = false`) or Binary (`is_binary = true`) format.
    pub fn save_with_options(&mut self, path: impl AsRef<Path>, is_binary: bool) -> Result<()> {
        if !self.drawing_variables.acad_ver.is_supported() {
            return Err(DxfError::VersionNotSupported {
                version: self.drawing_variables.acad_ver.to_string(),
            });
        }
        let file = File::create(path)?;
        self.save_to_writer(BufWriter::with_capacity(64 * 1024, file), is_binary)
    }

    /// Builds anonymous `*D<n>` geometry blocks for all dimensions missing one.
    pub fn build_all_dimension_blocks(&mut self) {
        let mut next_idx = 1usize;
        let mut new_blocks = Vec::new();
        for ent in self.entities.all_mut() {
            if let EntityObject::Dimension(dim) = ent {
                if dim.block_name.is_empty() {
                    let bname = format!("*D{next_idx}");
                    next_idx += 1;
                    let style = self
                        .dimension_styles
                        .get(&dim.style)
                        .cloned()
                        .unwrap_or_else(DimensionStyle::default_style);
                    let blk = DimensionBlock::build(dim, &style, &bname);
                    dim.block_name = bname;
                    new_blocks.push(blk);
                }
            }
        }
        for blk in new_blocks {
            self.blocks.insert(blk);
        }
    }

    /// Writes the DXF document to any `Write` sink in ASCII or Binary format.
    pub fn save_to_writer<W: Write>(&mut self, writer: W, is_binary: bool) -> Result<()> {
        if self.build_dimension_blocks {
            self.build_all_dimension_blocks();
        }
        self.assign_all_handles();
        DxfWriter::write(self, writer, is_binary)
    }

    /// Serializes the DXF document directly into a `Vec<u8>`.
    pub fn save_to_bytes(&mut self, is_binary: bool) -> Result<Vec<u8>> {
        let mut buf = Vec::with_capacity(16 * 1024);
        self.save_to_writer(&mut buf, is_binary)?;
        Ok(buf)
    }
}

impl Default for DxfDocument {
    fn default() -> Self {
        Self::new()
    }
}
