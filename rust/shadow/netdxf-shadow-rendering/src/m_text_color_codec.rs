impl MTextColorCodec {
    /// Returns opaque ARGB for ACI 1..=255. ByBlock (0), ByLayer (256), and invalid indices return `None`.
    pub fn resolve_indexed(index: i32) -> Option<u32> {
        if (1..=255).contains(&index) {
            Some(INDEXED_COLORS[(index - 1) as usize])
        } else {
            None
        }
    }

    /// Decodes MTEXT's 24-bit true color (`0x00BBGGRR`) into `0xAARRGGBB`.
    pub fn decode_true_color(value: i32) -> Option<u32> {
        if !(0..=0x00ff_ffff).contains(&value) {
            return None;
        }
        let packed = value as u32;
        Some(
            0xff00_0000
                | ((packed & 0xff) << 16)
                | (packed & 0xff00)
                | ((packed >> 16) & 0xff),
        )
    }
}
