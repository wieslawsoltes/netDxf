"""Live ribbon docking, expansion, context customization and Alt qualification."""
import json
from playwright.sync_api import expect
from workspace_layout_browser_checks import drawing_identity, ribbon_mode, settled


def verify_ribbon_workspace(page, output, state, command, wait_state, idle, check):
    baseline = drawing_identity(state())
    original_viewport = page.viewport_size
    original_mode = page.locator('#ribbon').get_attribute('data-mode')
    original_tab = page.locator('#ribbon-tabs [aria-selected="true"]').get_attribute('data-tab')
    original_preferences = page.evaluate("localStorage.getItem('netdxf-cad-ribbon-v1')")
    original_lock = page.evaluate("JSON.parse(localStorage.getItem('netdxf-cad-shell-v1')||'{}').lockUi||0")
    host = page.locator('.ribbon-host')
    menu = page.locator('.ribbon-context-menu')

    def preferences():
        return page.evaluate("JSON.parse(localStorage.getItem('netdxf-cad-ribbon-v1'))")

    def apply_preferences(value):
        page.evaluate("shadowStudioAgentUi.execute('ui.action', {name:'ribbon-customize'})")
        expect(page.locator('#dialog-title')).to_have_text('Customize ribbon')
        modal = page.locator('#dialog')
        if value:
            modal.get_by_label('Import ribbon customization', exact=True).set_input_files({
                'name': 'workspace-ribbon.json', 'mimeType': 'application/json', 'buffer': value.encode()})
            expect(modal.get_by_role('status')).to_contain_text('Imported into the draft')
        else:
            modal.get_by_role('button', name='Reset ribbon draft', exact=True).click()
        page.locator('#dialog-submit').click()
        expect(modal).not_to_be_visible()
        settled(page)

    def context(target=None):
        (target or page.locator('#ribbon-tabs')).click(button='right')
        expect(menu).to_be_visible()

    def dock(value):
        context(page.locator('.ribbon-host-header') if host.get_attribute('data-placement') != 'top' else None)
        menu.get_by_role('menuitem', name='Dock ribbon ›', exact=True).click()
        menu.get_by_role('menuitemcheckbox', name='Floating' if value == 'float' else f'Dock {value}', exact=True).click()
        settled(page)

    def drag(locator, dx=0, dy=0, *, target=None, cancel=False, ctrl=False):
        box = locator.bounding_box()
        x, y = box['x'] + min(8, box['width'] / 2), box['y'] + box['height'] / 2
        page.mouse.move(x, y)
        if ctrl:
            page.keyboard.down('Control')
        page.mouse.down()
        destination = target or (x + dx, y + dy)
        page.mouse.move(*destination, steps=8)
        if cancel:
            page.keyboard.press('Escape')
        page.mouse.up()
        if ctrl:
            page.keyboard.up('Control')
        settled(page)

    def cancel_command():
        page.evaluate("shadowStudioAgentUi.execute('command.cancel', {clearSelection:false})")
        expect(page.locator('#prompt')).to_have_text('Command:')
        idle()

    try:
        command('LOCKUI 0', False)
        apply_preferences(None)
        page.set_viewport_size({'width': 1600, 'height': 1000})
        ribbon_mode(page, 'Full ribbon', 'full')
        page.get_by_role('tab', name='Home', exact=True).click()
        settled(page)
        page.set_viewport_size({'width': 1280, 'height': 900})
        for tab in ['Home', 'Insert', 'Annotate', 'Graph', 'View', 'Manage', 'Output']:
            page.get_by_role('tab', name=tab, exact=True).click()
            settled(page)
            expect(page.locator('#ribbon .ribbon-group.collapsed')).to_have_count(0)
        check('all seven standard ribbon tabs keep their primary panels expanded at 1280px')
        page.set_viewport_size({'width': 1600, 'height': 1000})
        page.get_by_role('tab', name='Home', exact=True).click()
        settled(page)
        page.evaluate("window.__ribbonNodes=[document.querySelector('.document-bar'),document.getElementById('workspace'),document.querySelector('.statusbar'),document.getElementById('command-input')]")

        grip = page.locator('.ribbon-bar-grip')
        drag(grip, 280, 220)
        expect(host).to_have_attribute('data-placement', 'float')
        check('whole ribbon tears off by pointer capture and persists floating placement', preferences()['host']['placement'] == 'float')
        saved = preferences()['host']
        drag(page.locator('.ribbon-host-grip'), 70, 45, cancel=True)
        check('Escape cancels whole-ribbon drag without saving its preview', preferences()['host'] == saved)
        page.get_by_role('button', name='Toggle floating ribbon orientation', exact=True).click()
        expect(host).to_have_attribute('data-axis', 'vertical')
        width = host.bounding_box()['width']
        page.get_by_role('button', name='Resize ribbon', exact=True).press('ArrowRight')
        check('floating orientation and keyboard resize persist their independent dimensions',
              preferences()['host']['orientation'] == 'vertical' and host.bounding_box()['width'] >= width + 9)
        page.screenshot(path=str(output / 'ribbon-floating-vertical.png'))

        dock('left')
        expect(host).to_have_attribute('data-placement', 'left')
        left = host.bounding_box()
        central = page.locator('.ribbon-workspace-body').bounding_box()
        check('left ribbon docking reserves a vertical strip beside the same central document nodes',
              abs(central['x'] - left['width']) < 2 and page.evaluate("__ribbonNodes.every(node=>node.isConnected)"))
        page.screenshot(path=str(output / 'ribbon-docked-left.png'))
        ribbon_mode(page, 'Tabs only', 'tabs')
        width = page.locator('.ribbon-workspace-body').bounding_box()['width']
        check('minimizing a vertical ribbon releases its content width to the drawing', host.bounding_box()['width'] <= 34)
        page.get_by_role('tab', name='Home', exact=True).click()
        settled(page)
        expect(page.locator('#ribbon')).to_be_visible()
        check('vertical tabs reveal a temporary overlay without moving the drawing column',
              abs(page.locator('.ribbon-workspace-body').bounding_box()['width'] - width) < 2)
        page.locator('#ribbon-tabs [aria-selected="true"]').press('Escape')
        ribbon_mode(page, 'Full ribbon', 'full')
        dock('right')
        expect(host).to_have_attribute('data-placement', 'right')
        check('right ribbon docking preserves the viewport and command editor objects', page.evaluate("__ribbonNodes[1]===document.getElementById('workspace')&&__ribbonNodes[3]===document.getElementById('command-input')"))
        page.set_viewport_size({'width': 390, 'height': 800})
        settled(page)
        expect(host).to_have_attribute('data-placement', 'float')
        check('compact screens temporarily float a saved side dock within visible bounds',
              preferences()['host']['placement'] == 'right' and host.bounding_box()['x'] >= 4 and host.bounding_box()['x'] + host.bounding_box()['width'] <= 386)
        page.set_viewport_size({'width': 1600, 'height': 1000})
        expect(host).to_have_attribute('data-placement', 'right')
        dock('top')

        context()
        menu.get_by_role('menuitemcheckbox', name='Allow Docking', exact=True).click()
        expect(host).to_have_attribute('data-placement', 'float')
        dock('top')
        check('Allow Docking controls whole-ribbon docking without losing its prior workspace', host.get_attribute('data-placement') == 'float')
        context(page.locator('.ribbon-host-header'))
        menu.get_by_role('menuitemcheckbox', name='Allow Docking', exact=True).click()
        dock('top')

        command('LOCKUI 1', False)
        before = preferences()['host']
        drag(page.locator('.ribbon-bar-grip'), 200, 180)
        check('LOCKUI docked toolbar bit prevents whole-ribbon tear-off', preferences()['host'] == before)
        box = page.locator('.ribbon-bar-grip').bounding_box()
        x, y = box['x'] + 6, box['y'] + box['height'] / 2
        page.keyboard.down('Control')
        page.mouse.move(x, y)
        page.mouse.down()
        page.mouse.move(x + 200, y + 180, steps=6)
        page.keyboard.up('Control')
        settled(page)
        released = preferences()['host']
        page.mouse.move(x + 280, y + 240, steps=4)
        page.mouse.up()
        settled(page)
        expect(host).to_have_attribute('data-placement', 'float')
        check('Ctrl explicitly overrides locked ribbon movement')
        check('releasing Ctrl immediately ends a temporary ribbon lock override', preferences()['host'] == released)
        command('LOCKUI 0', False)
        dock('top')

        modify = page.locator('#ribbon [data-panel="Modify"]')
        modify.get_by_role('button', name='Expand Modify panel', exact=True).press('ArrowDown')
        popup = page.locator('.ribbon-slideout-popup')
        expect(popup.locator('[data-command="BREAK"]')).to_be_focused()
        page.locator('#ribbon [data-command="LINE"]').click()
        expect(popup).to_have_count(0)
        cancel_command()
        check('panel-title expansion exposes additional commands and closes on another panel')
        modify.get_by_role('button', name='Expand Modify panel', exact=True).click()
        popup.get_by_role('button', name='Keep Modify panel expanded', exact=True).click()
        expect(popup.get_by_role('button', name='Keep Modify panel expanded', exact=True)).to_have_attribute('aria-pressed', 'true')
        page.get_by_role('tab', name='View', exact=True).click()
        expect(popup).to_have_count(0)
        page.get_by_role('tab', name='Home', exact=True).click()
        expect(popup).to_be_visible()
        check('pinned panel expansion is saved and restored on returning to its source tab', preferences()['expanded'] == [{'tab': 'Home', 'panel': 'Modify'}])
        page.screenshot(path=str(output / 'ribbon-pinned-panel.png'))
        popup.locator('[data-command="BREAK"]').click()
        expect(page.locator('#prompt')).not_to_have_text('Command:')
        cancel_command()
        popup.get_by_role('button', name='Close Modify expanded panel', exact=True).click()
        expect(popup).to_have_count(0)
        check('expanded panel executes the original command and explicitly unpins on close', not preferences()['expanded'])

        context(page.locator('#ribbon [data-panel="Hatch"] .ribbon-group-title'))
        menu.get_by_role('menuitem', name='Hide panel', exact=True).click()
        expect(page.locator('#ribbon [data-panel="Hatch"]')).to_have_count(0)
        context()
        menu.get_by_role('menuitem', name='Show Panels ›', exact=True).click()
        menu.get_by_role('menuitemcheckbox', name='Hatch', exact=True).click()
        expect(page.locator('#ribbon [data-panel="Hatch"]')).to_be_visible()
        context(page.get_by_role('tab', name='Output', exact=True))
        menu.get_by_role('menuitem', name='Hide tab', exact=True).click()
        expect(page.get_by_role('tab', name='Output', exact=True)).to_have_count(0)
        context()
        menu.get_by_role('menuitem', name='Show Tabs ›', exact=True).click()
        expect(menu.get_by_role('menuitemcheckbox', name='Home', exact=True)).to_be_disabled()
        menu.get_by_role('menuitemcheckbox', name='Output', exact=True).click()
        check('context Show Tabs and Show Panels recover hidden controls and protect Home')

        draw_title = page.locator('#ribbon [data-panel="Draw"] .ribbon-group-title').bounding_box()
        drag(modify.locator('.ribbon-group-title'), target=(draw_title['x'] + 4, draw_title['y'] + draw_title['height'] / 2))
        check('dragging panel titles reorders the existing panels within the ribbon', page.locator('#ribbon>.ribbon-group').first.get_attribute('data-panel') == 'Modify')
        insert = page.get_by_role('tab', name='Insert', exact=True).bounding_box()
        drag(page.get_by_role('tab', name='View', exact=True), target=(insert['x'] + 2, insert['y'] + insert['height'] / 2))
        order = page.locator('#ribbon-tabs [data-tab]').evaluate_all('nodes=>nodes.map(node=>node.dataset.tab)')
        check('dragging ribbon tabs saves their new order', order.index('View') < order.index('Insert'))

        page.get_by_role('tab', name='Home', exact=True).click()
        context(page.locator('#ribbon [data-panel="Draw"] .ribbon-group-title'))
        menu.get_by_role('menuitem', name='Float panel', exact=True).click()
        floating = page.get_by_role('region', name='Draw floating ribbon panel', exact=True)
        floating.get_by_role('button', name='Toggle Draw panel orientation', exact=True).click()
        expect(floating).to_have_attribute('data-orientation', 'vertical')
        page.get_by_role('tab', name='View', exact=True).click()
        expect(floating).to_be_visible()
        page.get_by_role('tab', name='Home', exact=True).click()
        ribbon_bounds = page.locator('#ribbon').bounding_box()
        drag(floating.get_by_role('button', name='Move floating Draw panel', exact=True), target=(ribbon_bounds['x'] + 80, ribbon_bounds['y'] + 45))
        expect(floating).to_have_count(0)
        check('oriented floating panels survive tab changes and return by dragging onto the ribbon', not preferences()['floating'])

        line = page.locator('#ribbon [data-command="LINE"]')
        context(line)
        add = menu.get_by_role('menuitem', name='Add to Quick Access Toolbar', exact=True)
        was_pinned = not add.count()
        menu.get_by_role('menuitem', name='Remove from Quick Access Toolbar' if was_pinned else 'Add to Quick Access Toolbar', exact=True).click()
        context(line)
        expect(menu.get_by_role('menuitem', name='Add to Quick Access Toolbar' if was_pinned else 'Remove from Quick Access Toolbar', exact=True)).to_be_visible()
        menu.get_by_role('menuitem', name='Add to Quick Access Toolbar' if was_pinned else 'Remove from Quick Access Toolbar', exact=True).click()
        check('ribbon context pins and unpins exact catalog command identities in Quick Access')

        page.keyboard.press('Alt')
        expect(page.locator('.ribbon-keytips')).to_be_visible()
        page.keyboard.press('h')
        settled(page)
        expect(line).to_have_attribute('data-ribbon-keytip', 'LI')
        page.keyboard.type('li')
        expect(page.locator('.ribbon-keytips')).to_have_count(0)
        expect(page.locator('#prompt')).not_to_have_text('Command:')
        cancel_command()
        check('bare Alt then Home command KeyTips invoke the original drawing command')
        page.keyboard.press('Alt+h')
        settled(page)
        expect(line).to_have_attribute('data-ribbon-keytip', 'LI')
        page.keyboard.press('Escape')
        page.keyboard.press('Escape')
        expect(page.locator('.ribbon-keytips')).to_have_count(0)
        page.keyboard.press('Alt')
        page.keyboard.press('f')
        expect(page.locator('#shell-popup')).to_be_visible()
        page.keyboard.press('Escape')
        page.keyboard.press('Escape')
        page.keyboard.press('Escape')
        check('Alt chords and layered Escape navigate ribbon and application-menu KeyTips')
        polar = page.locator('#drafting-modes [data-mode-key="polar"]')
        before_polar = polar.get_attribute('aria-pressed')
        page.keyboard.press('Alt')
        page.keyboard.press('F10')
        expect(page.locator('.ribbon-keytips')).to_have_count(0)
        check('F10 remains Polar tracking even while KeyTips are visible', polar.get_attribute('aria-pressed') != before_polar)
        page.keyboard.press('F10')
        page.set_viewport_size({'width': 320, 'height': 740})
        page.get_by_role('tab', name='Home', exact=True).click()
        page.keyboard.press('Alt')
        page.keyboard.press('m')
        settled(page)
        expect(page.get_by_role('tab', name='Manage', exact=True)).to_have_attribute('aria-selected', 'true')
        expect(page.locator('.ribbon-keytips')).to_be_visible()
        check('Alt reaches an initially offscreen tab at 320px and keeps its next-level KeyTips active')
        page.keyboard.press('Escape')
        page.keyboard.press('Escape')
        check('ribbon workspace interactions preserve drawing identity and undo history', drawing_identity(state()) == baseline)
    finally:
        page.keyboard.press('Escape')
        page.keyboard.press('Escape')
        cancel_command()
        command(f'LOCKUI {original_lock}', False)
        page.set_viewport_size(original_viewport)
        apply_preferences(original_preferences)
        modes = {'full': 'Full ribbon', 'buttons': 'Panel buttons', 'titles': 'Panel titles', 'tabs': 'Tabs only'}
        ribbon_mode(page, modes[original_mode], original_mode)
        page.evaluate("key=>document.querySelectorAll('#ribbon-tabs [data-tab]').forEach(node=>{if(node.dataset.tab===key&&!node.disabled)node.click();})", original_tab)
        idle()
