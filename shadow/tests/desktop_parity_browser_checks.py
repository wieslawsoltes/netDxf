"""Desktop shell interaction qualification shared by native and static WASM hosts."""
from playwright.sync_api import expect
from browser_ui import wait_for_ui
from workspace_layout_browser_checks import drawing_identity, settled


def verify_desktop_parity(page, output, state, command, wait_state, idle, check):
    baseline = drawing_identity(state())
    viewport_size = page.viewport_size
    popup = page.locator('#shell-popup')
    line = page.locator('#command-line')
    command_input = page.locator('#command-input')

    def prefs():
        return page.evaluate("JSON.parse(localStorage.getItem('netdxf-cad-shell-v1'))")

    def ui(name):
        page.evaluate("name=>shadowStudioAgentUi.execute('ui.action',{name})", name)
        settled(page)

    def submit(text):
        command(text, False)
        settled(page)

    def command_menu(label):
        page.locator('#command-grip').click(button='right')
        popup.get_by_role('menuitemradio', name=label, exact=True).click()
        settled(page)

    def quick_menu():
        page.locator('#quick-access [data-access-control="customize"]').click()
        expect(popup).to_have_attribute('aria-label', 'Customize Quick Access')

    def drag(locator, dx, dy):
        box = locator.bounding_box()
        x, y = box['x'] + box['width']/2, box['y'] + box['height']/2
        page.mouse.move(x, y);page.mouse.down();page.mouse.move(x+dx, y+dy, steps=6);page.mouse.up()
        settled(page)

    try:
        page.set_viewport_size({'width': 1600, 'height': 1000})
        submit('WSAUTOSAVE 0')
        page.locator('#workspace-switch').click()
        popup.get_by_role('menuitemradio', name='Drafting & Annotation', exact=True).click()
        settled(page)
        quick_menu()
        popup.get_by_role('menuitem', name='Show Quick Access below ribbon', exact=True).click()
        expect(page.locator('#quick-access-below #quick-access')).to_be_visible()
        check('Quick Access moves below the ribbon while retaining its live toolbar', prefs()['quickAccessBelow'])
        quick_menu()
        popup.get_by_role('menuitemcheckbox', name='Zoom extents', exact=True).click()
        quick_menu()
        popup.get_by_role('menuitem', name='Show Quick Access above ribbon', exact=True).click()
        page.set_viewport_size({'width': 390, 'height': 844});settled(page)
        page.locator('#quick-access [data-access-control="overflow"]').click()
        expect(popup).to_have_attribute('aria-label', 'More Quick Access commands')
        popup.get_by_role('menuitem', name='Zoom extents', exact=True).click()
        check('Quick Access overflow directly executes its registered hidden commands', drawing_identity(state()) == baseline)
        page.set_viewport_size({'width': 1600, 'height': 1000});settled(page)
        quick_menu()
        popup.get_by_role('menuitemcheckbox', name='Zoom extents', exact=True).click()
        expect(page.locator('.titlebar #quick-access')).to_be_visible()
        submit('MENUBAR 1')
        menu = page.get_by_role('menubar', name='Application menu bar')
        expect(menu).to_be_visible()
        menu.get_by_role('menuitem', name='File', exact=True).focus()
        page.keyboard.press('ArrowDown')
        expect(popup).to_have_attribute('aria-label', 'File menu')
        page.keyboard.press('ArrowRight')
        expect(popup).to_have_attribute('aria-label', 'Edit menu')
        page.keyboard.press('Escape')
        expect(menu.get_by_role('menuitem', name='Edit', exact=True)).to_be_focused()
        check('optional menu bar supports keyboard opening switching and focus recovery')
        submit('MENUBAR 0')

        command_input.fill('LINE 10,20')
        command_input.evaluate('node=>{window.__retainedCommand=node;node.focus();node.setSelectionRange(5,7)}')
        page.locator('#command-dock-toggle').evaluate('node=>node.click()')
        check('floating preserves the existing command editor selection', command_input.evaluate('node=>node===window.__retainedCommand&&node.selectionStart===5&&node.selectionEnd===7'))
        command_input.fill('')
        command_menu('Dock at top')
        check('command window docks above the drawing with the splitter below it', line.bounding_box()['y'] < page.locator('#viewport').bounding_box()['y'] and page.locator('#command-splitter').bounding_box()['y'] > line.bounding_box()['y'])
        before = line.bounding_box()['height']
        drag(page.locator('#command-splitter'), 0, 30)
        check('top-docked command splitter grows toward the drawing', line.bounding_box()['height'] > before+20)
        before = line.bounding_box()['height']
        splitter = page.locator('#command-splitter').bounding_box()
        x, y = splitter['x']+splitter['width']/2, splitter['y']+splitter['height']/2
        page.mouse.move(x, y);page.mouse.down();page.mouse.move(x, y+20, steps=4)
        page.evaluate("window.dispatchEvent(new Event('blur'))")
        page.mouse.up();settled(page)
        check('window blur cancels splitter resizing and removes its gesture handlers', abs(line.bounding_box()['height']-before) < 2)
        submit('LOCKUI 2')
        splitter = page.locator('#command-splitter').bounding_box()
        x, y = splitter['x']+splitter['width']/2, splitter['y']+splitter['height']/2
        page.keyboard.down('Control');page.mouse.move(x, y);page.mouse.down();page.mouse.move(x, y+15, steps=3)
        page.keyboard.up('Control');settled(page)
        completed = line.bounding_box()['height']
        page.mouse.move(x, y+45, steps=3);page.mouse.up();settled(page)
        check('releasing Ctrl finishes a docked command splitter lock override', completed > before+8 and abs(line.bounding_box()['height']-completed) < 2 and prefs()['lockUi'] == 2)
        submit('LOCKUI 0')
        command_menu('Float command window')
        before = line.bounding_box()
        drag(page.locator('[data-command-resize="nw"]'), -25, -20)
        after = line.bounding_box()
        check('northwest command resizing retains the opposite edges', after['width'] > before['width']+15 and abs(after['x']+after['width']-before['x']-before['width']) < 2 and abs(after['y']+after['height']-before['y']-before['height']) < 2)
        grip = page.locator('#command-grip').bounding_box()
        x, y = grip['x']+grip['width']/2, grip['y']+grip['height']/2
        page.keyboard.down('Control');page.mouse.move(x, y);page.mouse.down();page.mouse.move(x+15, y, steps=3)
        page.keyboard.up('Control');settled(page)
        released = line.bounding_box()['x']
        page.mouse.move(x+35, y, steps=3);page.mouse.up();settled(page)
        check('an unlocked command-window drag continues after releasing the docking-suppression modifier', line.bounding_box()['x'] > released+12)
        submit('LOCKUI 8')
        before = line.bounding_box()
        page.locator('#command-grip').focus();page.keyboard.press('ArrowRight')
        check('floating-window lock prevents accidental command window movement', abs(line.bounding_box()['x']-before['x']) < 1)
        page.keyboard.press('Control+ArrowRight')
        check('Ctrl temporarily overrides the window lock without changing saved categories', line.bounding_box()['x'] > before['x']+5 and prefs()['lockUi'] == 8)
        submit('LOCKUI 0')
        command_menu('Anchor at bottom')
        page.set_viewport_size({'width': 1366, 'height': 800});settled(page)
        area = page.locator('#drawing-area').bounding_box();anchor = line.bounding_box()
        check('anchored command window follows the drawing edge on host resize', abs(anchor['y']+anchor['height']-(area['y']+area['height']-4)) < 2)
        page.set_viewport_size({'width': 1600, 'height': 1000});settled(page)
        page.locator('#command-grip').click(button='right')
        popup.get_by_role('menuitemcheckbox', name='Allow docking', exact=True).click()
        expect(line).to_have_attribute('data-command-mode', 'float')
        page.locator('#command-grip').click(button='right')
        expect(popup.get_by_role('menuitemradio', name='Dock at top', exact=True)).to_be_disabled()
        popup.get_by_role('menuitemcheckbox', name='Allow docking', exact=True).click()
        check('disabling command docking floats the window and disables docking destinations')
        page.locator('#command-grip').click(button='right')
        popup.get_by_role('menuitem', name='Transparency…', exact=True).click()
        popup.get_by_role('slider', name='Inactive opacity').evaluate("node=>{node.value='50';node.dispatchEvent(new Event('input',{bubbles:true}))}")
        page.keyboard.press('Escape');page.locator('#viewport').focus();page.mouse.move(700, 40)
        check('floating command opacity is persisted and uses inactive and active states', prefs()['commandWindow']['inactiveOpacity'] == .5 and float(line.evaluate('node=>getComputedStyle(node).opacity')) == .5)
        command_menu('Dock at bottom')
        ui('command-line-hide')
        page.keyboard.press('Control+F2')
        text_window = page.get_by_role('dialog', name='Command history window')
        expect(text_window).to_be_visible()
        expect(text_window.locator('pre')).to_contain_text('LOCKUI')
        text_window.get_by_role('menuitem', name='Focus command line', exact=True).click()
        expect(command_input).to_be_visible();expect(command_input).to_be_focused()
        check('full-size command history remains accessible with command line hidden and can restore input focus')
        page.locator('#workspace-switch').click()
        expect(popup).to_be_visible()
        page.keyboard.press('Control+F2')
        expect(text_window).to_be_visible();expect(popup).not_to_be_visible()
        page.keyboard.press('Escape')
        expect(text_window).not_to_be_visible();expect(page.locator('#workspace-switch')).to_be_focused()
        check('command history dismisses background menus and closes with one Escape restoring its launcher')

        ui('layers')
        page.keyboard.press('Control+1')
        expect(page.locator('[data-palette="Properties"]')).not_to_be_visible()
        expect(page.locator('[data-palette="Layers"]')).to_be_visible()
        page.keyboard.press('Control+1')
        expect(page.locator('[data-palette="Properties"]')).to_be_visible()
        check('Ctrl+1 toggles only Properties and keeps other palettes open')
        page.keyboard.press('Control+Shift+H')
        expect(line).not_to_be_visible()
        expect(page.locator('.ribbon-host')).not_to_be_visible()
        expect(page.locator('.document-bar')).not_to_be_visible()
        expect(page.locator('[data-palette="Properties"]')).not_to_be_visible()
        ui('properties')
        expect(page.locator('[data-palette="Properties"]')).to_be_visible()
        expect(page.locator('[data-palette="Layers"]')).not_to_be_visible()
        ui('properties-toggle')
        ui('palettes-show')
        expect(page.locator('[data-palette="Properties"]')).not_to_be_visible()
        expect(page.locator('[data-palette="Layers"]')).to_be_visible()
        expect(line).to_be_visible()
        expect(page.locator('.ribbon-host')).to_be_visible()
        expect(page.locator('.document-bar')).to_be_visible()
        check('Hide/Show restores command line ribbon and drawing tabs while respecting manually changed palettes')
        ui('properties')
        submit('FILETABCLOSE');expect(page.locator('.document-bar')).not_to_be_visible()
        submit('FILETAB');expect(page.locator('.document-bar')).to_be_visible()
        submit('RIBBONCLOSE');expect(page.locator('.ribbon-host')).not_to_be_visible()
        submit('RIBBON');expect(page.locator('.ribbon-host')).to_be_visible()
        submit('LAYOUTTAB 0');expect(page.locator('.layout-bar')).not_to_be_visible()
        submit('LAYOUTTAB 1');expect(page.locator('.layout-bar')).to_be_visible()
        check('typed UI recovery commands restore hidden ribbon drawing tabs and layout tabs')
        check('desktop presentation interactions preserve the drawing revision selection and undo history', drawing_identity(state()) == baseline)
    finally:
        page.keyboard.press('Escape')
        ui('command-line-show');ui('palettes-show')
        submit('LOCKUI 0');submit('WSAUTOSAVE 0')
        page.locator('#workspace-switch').click()
        popup.get_by_role('menuitemradio', name='Drafting & Annotation', exact=True).click()
        page.set_viewport_size(viewport_size)
        page.evaluate('delete window.__retainedCommand')
