using System;
using System.IO;
using System.Threading;
using netDxf.IO;

namespace netDxf
{
    /// <summary>Resource limits for explicitly materialized dimension-picture exports.</summary>
    public sealed class DxfDimensionPictureOptions
    {
        /// <summary>Creates bounded export settings. Existing ordinary Save behavior is unchanged.</summary>
        public DxfDimensionPictureOptions(int maximumPictures = 10000, int maximumPictureEntities = 200000,
            DxfRawOptions rawOptions = null)
        {
            if (maximumPictures < 1) throw new ArgumentOutOfRangeException(nameof(maximumPictures));
            if (maximumPictureEntities < 1) throw new ArgumentOutOfRangeException(nameof(maximumPictureEntities));
            this.MaximumPictures = maximumPictures;
            this.MaximumPictureEntities = maximumPictureEntities;
            this.RawOptions = rawOptions ?? new DxfRawOptions();
        }
        /// <summary>Maximum dimension pictures prepared in one export.</summary>
        public int MaximumPictures { get; }
        /// <summary>Maximum direct entities in the generated pictures.</summary>
        public int MaximumPictureEntities { get; }
        /// <summary>Encoded byte, tag-count and string-length limits.</summary>
        public DxfRawOptions RawOptions { get; }
    }

    public sealed partial class DxfDocument
    {
        /// <summary>Saves valid native dimension pictures without changing live dimension geometry.</summary>
        /// <param name="stream">Writable destination, left open.</param>
        /// <param name="isBinary">Whether to write binary rather than text DXF.</param>
        /// <param name="options">Optional materialization and serialization budgets.</param>
        /// <param name="cancellationToken">Checked between preparation, serialization and output stages.</param>
        /// <remarks>
        /// Missing pictures and pictures generated by this API are regenerated from detached dimensions.
        /// Existing unmarked pictures are preserved. A generated picture shared by multiple owners is
        /// rejected instead of silently rewriting another entity's presentation. Native writer methods
        /// generate both the pictures and their dimension headers; the raw tag API replaces only those
        /// dimension subclasses, without loading/reconstructing the document through the typed reader.
        /// Temporary picture registrations/content are restored before returning, including on failure.
        /// Ordinary writer handle/table housekeeping is not rolled back; callers must serialize access
        /// and reconcile it into their source session. No external resource files are loaded. This API
        /// buffers within the configured limits and propagates errors consistently in Debug and Release.
        /// A final destination I/O failure can leave a partial stream. This is not an atomic file save.
        /// </remarks>
        public void SaveWithDimensionPictures(Stream stream, bool isBinary = false,
            DxfDimensionPictureOptions options = null, CancellationToken cancellationToken = default(CancellationToken))
        {
            if (stream == null) throw new ArgumentNullException(nameof(stream));
            if (!stream.CanWrite) throw new ArgumentException("A writable destination is required.", nameof(stream));
            DxfDimensionPictureExport.Write(this, stream, isBinary, options ?? new DxfDimensionPictureOptions(), cancellationToken);
        }
    }
}
